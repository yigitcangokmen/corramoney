/**
 * Creates, or after a testnet reset re-funds, Corra's five channel accounts on Stellar TESTNET.
 * Secrets go to .env.testnet (CHANNEL_SECRETS, gitignored, never printed); public keys to
 * packages/shared/src/testnet-channels.ts. Idempotent.
 *
 * A channel is only the transaction source of a sponsored setup that creates an account: it pays
 * that fee and nothing else, so it holds only friendbot XLM, no trustline, no other signer.
 * `pnpm seed-testnet --force` rewrites .env.testnet whole: run this again afterwards (new keys).
 */
import * as S from '@stellar/stellar-sdk';
import { appendFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { TESTNET, TESTNET_BLEND, TESTNET_CHANNELS } from '../packages/shared/src';
import { envValue, loadOrFund } from './lib/pool';

const ENV_PATH = '.env.testnet';
const CHANNELS_TS = 'packages/shared/src/testnet-channels.ts';
const COUNT = 5;
/** Enough for thousands of setup fees (at most 4,000 stroops each). */
const MIN_XLM = 100;

function fail(message: string): never {
  console.error(`create-channels: ${message}`);
  process.exit(1);
}

/** The five channel keys: from CHANNEL_SECRETS, or new ones appended to .env.testnet before any funding. */
function channelKeys(): S.Keypair[] {
  // The line, not its value: an empty `CHANNEL_SECRETS=` is malformed, never a reason to append a second line.
  const present = /^CHANNEL_SECRETS=/m.test(readFileSync(ENV_PATH, 'utf8'));
  const line = envValue('CHANNEL_SECRETS');
  if (present) {
    if (!line) fail(`CHANNEL_SECRETS in ${ENV_PATH} is malformed; fix it by hand`);
    let keys: S.Keypair[];
    try {
      keys = line.split(',').map((s) => S.Keypair.fromSecret(s.trim()));
    } catch {
      fail(`CHANNEL_SECRETS in ${ENV_PATH} is malformed; fix it by hand`);
    }
    if (keys.length !== COUNT || new Set(keys.map((k) => k.publicKey())).size !== COUNT) {
      fail(`CHANNEL_SECRETS in ${ENV_PATH} is malformed; fix it by hand`);
    }
    return keys;
  }
  const keys = Array.from({ length: COUNT }, () => S.Keypair.random());
  // Written first: a run that fails while funding never loses the keys.
  const text = readFileSync(ENV_PATH, 'utf8');
  appendFileSync(ENV_PATH, `${text.endsWith('\n') ? '' : '\n'}CHANNEL_SECRETS=${keys.map((k) => k.secret()).join(',')}\n`);
  console.log(`5 new channel keys, CHANNEL_SECRETS appended to ${ENV_PATH}`);
  return keys;
}

async function main() {
  if (!existsSync(ENV_PATH)) fail('no .env.testnet: run pnpm seed-testnet first');
  const keys = channelKeys();
  // Team keys a channel must never be: the sponsor, the issuers, every other TESTNET account, the pool admin.
  const team = new Set<string>([
    ...(Object.values(TESTNET) as unknown[]).filter((v): v is string => typeof v === 'string' && S.StrKey.isValidEd25519PublicKey(v)),
    ...(TESTNET_BLEND?.admin ? [TESTNET_BLEND.admin] : []),
  ]);

  for (const k of keys) {
    const pk = k.publicKey();
    const a: any = await loadOrFund(pk);
    const why = (what: string) => fail(`channel ${pk}: ${what}`);
    if (team.has(pk)) why('is a team key');
    const native = a.balances.find((b: any) => b.asset_type === 'native');
    if (a.balances.length !== 1 || !native) why('holds a balance other than XLM');
    if (Number(native.balance) < MIN_XLM) why(`holds ${native.balance} XLM, below ${MIN_XLM}`);
    if (a.signers.length !== 1 || a.signers[0].key !== pk || a.signers[0].weight !== 1) why('signers are not exactly its own key with weight 1');
    const t = a.thresholds;
    if (t.low_threshold !== 0 || t.med_threshold !== 0 || t.high_threshold !== 0) why('thresholds are not 0/0/0');
    if (Number(a.subentry_count ?? a.num_subentries ?? 0) !== 0) why('has subentries');
    if (a.sponsor) why('is sponsored');
  }

  const pks = keys.map((k) => k.publicKey());
  if (pks.join(',') !== TESTNET_CHANNELS.join(',')) {
    writeFileSync(CHANNELS_TS, `// Generated by scripts/create-channels.ts on ${new Date().toISOString()}. Public Stellar TESTNET accounts, disclosed by design.
// Corra's channel accounts: transaction source of sponsored setups that create an account, nothing else.
export const TESTNET_CHANNELS: readonly string[] = [
${pks.map((pk) => `  '${pk}',`).join('\n')}
];
`);
    console.log(`wrote ${CHANNELS_TS}`);
  } else {
    console.log(`${CHANNELS_TS} already lists these five`);
  }
  console.log('Channel accounts (Stellar TESTNET):');
  for (const pk of pks) console.log(`  ${pk}  https://stellar.expert/explorer/testnet/account/${pk}`);
  console.log(`CHANNEL_SECRETS in ${ENV_PATH} (not printed)`);
}

main().catch((e) => fail((e as Error).message));
