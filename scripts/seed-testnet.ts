/**
 * Creates every testnet account and asset Corra needs, seeds the DEX, and writes:
 *   .env.testnet                      secrets (gitignored)
 *   packages/shared/src/testnet.ts    public addresses (committed, disclosed by design)
 *
 * Usage: pnpm seed-testnet [--force]          new random keys: new addresses, new SAC ids (a deliberate fresh start only)
 *        pnpm seed-testnet --reuse-keys [--dry-run]
 *                                             the keys already in .env.testnet: creates only what the chain lacks (after
 *                                             a testnet reset: everything), so every address and SAC id stays the same
 *        pnpm seed-testnet --keys-only        no .env.testnet yet: writes fresh keys and testnet.ts, submits nothing (rehearsal)
 */
import * as S from '@stellar/stellar-sdk';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { FIAT, type FiatCode } from '../packages/shared/src/corridors';
import { BASE_KEYS, envOf } from './lib/keys';
import { planSeed, ROLES, type Action, type Role } from './lib/seed-plan';
import { assetsOf, corridorPaths, readChainState } from './lib/testnet-state';

const HORIZON_URL = 'https://horizon-testnet.stellar.org';
const RPC_URL = 'https://soroban-testnet.stellar.org';
const NP = S.Networks.TESTNET;
const ENV_PATH = '.env.testnet';
const TESTNET_TS = 'packages/shared/src/testnet.ts';

const MM_USDC_BALANCE = 10_000_000;
const ANCHOR_MXN_BALANCE = 10_000_000 * FIAT.MXN.perUsd;
const OFFER_DEPTH_USD = 1_000_000;
const SPREAD = 0.0025;

const horizon = new S.Horizon.Server(HORIZON_URL);
const rpc = new S.rpc.Server(RPC_URL);

const amt = (n: number) => n.toFixed(7);
const price = (n: number) => n.toPrecision(12);

/** Friendbot is rate limited and flaky under parallel calls (CI), so a few retries with backoff. */
async function friendbot(pk: string) {
  for (let attempt = 1; ; attempt++) {
    const r = await fetch(`https://friendbot.stellar.org?addr=${encodeURIComponent(pk)}`,
      { signal: AbortSignal.timeout(30_000) }).catch(() => null);
    if (r?.ok) return;
    // A retry after a lost response finds the account already funded: that is success.
    if (r?.status === 400 && /already funded|createAccountAlreadyExist/i.test(await r.text().catch(() => ''))) return;
    if (attempt >= 4) throw new Error(`friendbot ${r?.status ?? 'unreachable'} for ${pk}`);
    await new Promise((done) => setTimeout(done, 2000 * attempt));
  }
}

async function submit(source: S.Keypair, ops: S.xdr.Operation[], label: string) {
  for (let i = 0; i < ops.length; i += 100) {
    const acct = await horizon.loadAccount(source.publicKey());
    const b = new S.TransactionBuilder(acct, { fee: '1000', networkPassphrase: NP }).setTimeout(120);
    ops.slice(i, i + 100).forEach((op) => b.addOperation(op));
    const tx = b.build();
    tx.sign(source);
    try {
      const r = await horizon.submitTransaction(tx);
      console.log(`  ${label}: ${r.hash}`);
    } catch (e: any) {
      const codes = e?.response?.data?.extras?.result_codes;
      throw new Error(`${label} failed: ${JSON.stringify(codes ?? e.message)}`);
    }
  }
}

async function deploySac(source: S.Keypair, asset: S.Asset): Promise<string> {
  const acct = await rpc.getAccount(source.publicKey());
  let tx = new S.TransactionBuilder(acct, { fee: '100000', networkPassphrase: NP })
    .addOperation(S.Operation.createStellarAssetContract({ asset }))
    .setTimeout(120)
    .build();
  tx = await rpc.prepareTransaction(tx);
  tx.sign(source);
  const sent = await rpc.sendTransaction(tx);
  if (sent.status === 'ERROR') throw new Error(`SAC ${asset.code} send error`);
  for (let i = 0; i < 30; i++) {
    await new Promise((r) => setTimeout(r, 2000));
    const got = await rpc.getTransaction(sent.hash);
    if (got.status === 'SUCCESS') {
      console.log(`  SAC ${asset.code}: ${sent.hash}`);
      return asset.contractId(NP);
    }
    if (got.status === 'FAILED') throw new Error(`SAC ${asset.code} failed: ${sent.hash}`);
  }
  throw new Error(`SAC ${asset.code} timed out: ${sent.hash}`);
}

/** packages/shared/src/testnet.ts for these public keys and SAC ids (the demo recipient line only when given). */
function renderTestnetTs(pk: Record<Role | 'clientDomainSigner', string>, sac: Record<string, string>, demoRecipient?: string) {
  return `// Generated by scripts/seed-testnet.ts on ${new Date().toISOString()}.
// Public testnet addresses of team-controlled accounts, disclosed by design.
export const TESTNET = {
  horizonUrl: '${HORIZON_URL}',
  rpcUrl: '${RPC_URL}',
  networkPassphrase: '${NP}',
  usdcIssuer: '${pk.usdcIssuer}',
  corridorIssuer: '${pk.corridorIssuer}',
  anchorDistribution: '${pk.anchorDistribution}',
  marketMaker: '${pk.marketMaker}',
  feeSponsor: '${pk.feeSponsor}',
  clientDomainSigner: '${pk.clientDomainSigner}',
${demoRecipient ? `  demoRecipient: '${demoRecipient}',\n` : ''}  sac: ${JSON.stringify(sac, null, 4).replace(/\n}/, '\n  }')},
} as const;
`;
}

const sacIds = (usdcIssuer: string, corridorIssuer: string) =>
  Object.fromEntries(Object.entries(assetsOf(usdcIssuer, corridorIssuer)).map(([code, a]) => [code, a.contractId(NP)]));

function fail(message: string): never {
  console.error(`seed-testnet: ${message}`);
  process.exit(1);
}

/** --keys-only: a fresh key set and its testnet.ts, nothing on chain (the rebuild then creates everything). */
function keysOnly() {
  if (existsSync(ENV_PATH)) fail(`${ENV_PATH} exists; --keys-only only starts a key set from nothing`);
  const kp = Object.fromEntries(Object.values(BASE_KEYS).map((field) => [field, S.Keypair.random()])) as Record<string, S.Keypair>;
  writeFileSync(ENV_PATH, [
    '# Generated by scripts/seed-testnet.ts --keys-only. Stellar TESTNET only. Never commit.',
    ...Object.entries(BASE_KEYS).map(([name, field]) => `${name}=${kp[field].secret()}`), '',
  ].join('\n'));
  const pk = Object.fromEntries(Object.entries(kp).map(([k, v]) => [k, v.publicKey()])) as any;
  writeFileSync(TESTNET_TS, renderTestnetTs(pk, sacIds(pk.usdcIssuer, pk.corridorIssuer)));
  console.log(`wrote ${ENV_PATH} (6 new keys, not printed) and ${TESTNET_TS}; nothing submitted`);
}

/**
 * --reuse-keys: the keys in .env.testnet, which must be the ones testnet.ts names (else the SOW's
 * addresses would silently change). Plans from the chain, runs only the planned actions, one
 * transaction per role and kind, and rewrites testnet.ts only when its content changes.
 */
async function reuseKeys(dryRun: boolean) {
  if (process.argv.includes('--force')) fail('--reuse-keys and --force exclude each other');
  if (!existsSync(ENV_PATH)) fail(`no ${ENV_PATH} to reuse`);
  const env = envOf(readFileSync(ENV_PATH, 'utf8'));
  const { TESTNET } = await import('../packages/shared/src/testnet');
  const kp = {} as Record<Role | 'clientDomainSigner', S.Keypair>;
  for (const [name, field] of Object.entries(BASE_KEYS)) {
    let k: S.Keypair;
    try {
      k = S.Keypair.fromSecret(env[name] ?? '');
    } catch {
      fail(`${name} is missing from ${ENV_PATH} or not a secret key`);
    }
    if (k.publicKey() !== (TESTNET as any)[field]) fail('.env.testnet and testnet.ts are from different seed runs');
    kp[field] = k;
  }
  const keys = Object.fromEntries(ROLES.map((r) => [r, kp[r].publicKey()])) as Record<Role, string>;
  const plan = planSeed(await readChainState(keys), keys);
  console.log(`plan (${plan.length} action${plan.length === 1 ? '' : 's'}):`);
  for (const a of plan) console.log(`  ${describe(a)}`);
  if (dryRun) {
    console.log('--dry-run: nothing submitted');
    return;
  }

  const assets = assetsOf(keys.usdcIssuer, keys.corridorIssuer);
  const issuerOf = (code: string) => (code === 'USDC' ? kp.usdcIssuer : kp.corridorIssuer);
  let txs = 0;
  let fundings = 0;
  const run = async (source: S.Keypair, ops: S.xdr.Operation[], label: string) => {
    await submit(source, ops, label);
    txs += Math.ceil(ops.length / 100);
  };
  const funds = plan.filter((a): a is Extract<Action, { kind: 'fund' }> => a.kind === 'fund');
  if (funds.length) {
    console.log('funding with friendbot');
    await Promise.all(funds.map((a) => friendbot(keys[a.role])));
    fundings = funds.length;
  }
  for (const a of plan) {
    if (a.kind === 'trust') await run(kp[a.role], a.codes.map((c) => S.Operation.changeTrust({ asset: assets[c] })), `${a.role} trustlines`);
  }
  // One transaction per issuer.
  const issues = plan.filter((a): a is Extract<Action, { kind: 'issue' }> => a.kind === 'issue');
  for (const issuer of ['usdcIssuer', 'corridorIssuer'] as const) {
    const mine = issues.filter((a) => (a.code === 'USDC') === (issuer === 'usdcIssuer'));
    if (mine.length) {
      await run(kp[issuer], mine.map((a) => S.Operation.payment({ destination: keys[a.to], asset: assets[a.code], amount: a.amount })), `issue ${mine.map((a) => a.code).join(', ')}`);
    }
  }
  for (const a of plan) {
    if (a.kind !== 'offers') continue;
    const byId = Object.fromEntries(Object.entries(assets).map(([code, asset]) => [`${code}:${asset.getIssuer()}`, code]));
    await run(kp.marketMaker, a.pairs.map((p) => {
      const [selling, buying] = [byId[p.selling], byId[p.buying]];
      const fiat = (selling === 'USDC' ? buying : selling).replace(/^TEST/, '') as FiatCode;
      return selling === 'USDC' ? usdcOffer(assets.USDC, assets[buying], FIAT[fiat].perUsd) : fiatOffer(assets[selling], assets.USDC, FIAT[fiat].perUsd);
    }), 'offers');
  }
  for (const a of plan) {
    if (a.kind !== 'sac') continue;
    const id = await deploySac(issuerOf(a.code), assets[a.code]);
    txs++;
    if (id !== (TESTNET.sac as Record<string, string>)[a.code]) fail(`SAC ${a.code} is ${id}, but testnet.ts names ${(TESTNET.sac as Record<string, string>)[a.code]}`);
  }

  console.log('verifying strict-receive paths (recipient gets 1000)');
  for (const p of await corridorPaths(keys.corridorIssuer)) {
    if (!p.sourceAmount) fail(`no path TESTMXN -> ${p.code}`);
    console.log(`  ${p.hops}: pay ${p.sourceAmount} TESTMXN`);
  }

  const pk = Object.fromEntries(Object.entries(kp).map(([k, v]) => [k, v.publicKey()])) as Record<Role | 'clientDomainSigner', string>;
  const next = renderTestnetTs(pk, sacIds(pk.usdcIssuer, pk.corridorIssuer), (TESTNET as { demoRecipient?: string }).demoRecipient);
  const body = (t: string) => t.slice(t.indexOf('\n') + 1);
  if (body(next) !== body(readFileSync(TESTNET_TS, 'utf8'))) {
    writeFileSync(TESTNET_TS, next);
    console.log(`wrote ${TESTNET_TS}`);
  } else {
    console.log(`${TESTNET_TS} unchanged`);
  }
  console.log(`seed-testnet --reuse-keys: ${txs} transactions, ${fundings} fundings`);
}

function describe(a: Action): string {
  switch (a.kind) {
    case 'fund': return `fund ${a.role} (friendbot)`;
    case 'trust': return `${a.role} trusts ${a.codes.join(', ')}`;
    case 'issue': return `issue ${a.amount} ${a.code} to ${a.to}`;
    case 'offers': return `${a.pairs.length} market-maker offer pair(s)`;
    case 'sac': return `deploy the ${a.code} Stellar Asset Contract`;
  }
}

/** MM sells USDC, asks slightly more fiat than mid (price = fiat per USDC). */
const usdcOffer = (usdc: S.Asset, fiat: S.Asset, r: number) =>
  S.Operation.manageSellOffer({ selling: usdc, buying: fiat, amount: amt(OFFER_DEPTH_USD), price: price(r * (1 + SPREAD)) });
/** MM sells fiat, asks slightly more USDC than mid (price = USDC per fiat). */
const fiatOffer = (fiat: S.Asset, usdc: S.Asset, r: number) =>
  S.Operation.manageSellOffer({ selling: fiat, buying: usdc, amount: amt(OFFER_DEPTH_USD * r), price: price((1 / r) * (1 + SPREAD)) });

async function main() {
  if (process.argv.includes('--keys-only')) return keysOnly();
  if (process.argv.includes('--reuse-keys')) return reuseKeys(process.argv.includes('--dry-run'));
  if (existsSync(ENV_PATH) && !process.argv.includes('--force')) {
    console.error(`${ENV_PATH} exists. To keep its keys (after a testnet reset): pnpm seed-testnet --reuse-keys. `
      + 'Re-run with --force only to create a fresh set of accounts (new addresses and SAC ids).');
    process.exit(1);
  }

  const kp = {
    usdcIssuer: S.Keypair.random(),
    corridorIssuer: S.Keypair.random(),
    anchorDistribution: S.Keypair.random(),
    marketMaker: S.Keypair.random(),
    feeSponsor: S.Keypair.random(),
    clientDomainSigner: S.Keypair.random(),
  };

  // Written first so a run that fails halfway never loses the keys of accounts it already funded.
  writeFileSync(
    ENV_PATH,
    [
      '# Generated by scripts/seed-testnet.ts. Stellar TESTNET only. Never commit.',
      `USDC_ISSUER_SECRET=${kp.usdcIssuer.secret()}`,
      `CORRIDOR_ISSUER_SECRET=${kp.corridorIssuer.secret()}`,
      `ANCHOR_DISTRIBUTION_SECRET=${kp.anchorDistribution.secret()}`,
      `MARKET_MAKER_SECRET=${kp.marketMaker.secret()}`,
      `FEE_SPONSOR_SECRET=${kp.feeSponsor.secret()}`,
      `CLIENT_DOMAIN_SIGNING_SECRET=${kp.clientDomainSigner.secret()}`,
      '',
    ].join('\n'),
  );

  console.log('1/6 funding accounts with friendbot');
  await Promise.all(
    [kp.usdcIssuer, kp.corridorIssuer, kp.anchorDistribution, kp.marketMaker, kp.feeSponsor].map((k) =>
      friendbot(k.publicKey()),
    ),
  );

  const usdc = new S.Asset('USDC', kp.usdcIssuer.publicKey());
  const fiats = Object.keys(FIAT) as FiatCode[];
  const corridor = Object.fromEntries(
    fiats.map((f) => [f, new S.Asset(FIAT[f].code, kp.corridorIssuer.publicKey())]),
  ) as Record<FiatCode, S.Asset>;

  console.log('2/6 trustlines');
  await submit(
    kp.marketMaker,
    [usdc, ...fiats.map((f) => corridor[f])].map((asset) => S.Operation.changeTrust({ asset })),
    'market-maker trustlines',
  );
  await submit(kp.anchorDistribution, [S.Operation.changeTrust({ asset: corridor.MXN }), S.Operation.changeTrust({ asset: corridor.PHP })], 'anchor trustlines');

  console.log('3/6 issuing');
  await submit(
    kp.usdcIssuer,
    [S.Operation.payment({ destination: kp.marketMaker.publicKey(), asset: usdc, amount: amt(MM_USDC_BALANCE) })],
    'issue USDC',
  );
  await submit(
    kp.corridorIssuer,
    [
      ...fiats.map((f) =>
        S.Operation.payment({
          destination: kp.marketMaker.publicKey(),
          asset: corridor[f],
          amount: amt(MM_USDC_BALANCE * FIAT[f].perUsd),
        }),
      ),
      S.Operation.payment({
        destination: kp.anchorDistribution.publicKey(),
        asset: corridor.MXN,
        amount: amt(ANCHOR_MXN_BALANCE),
      }),
    ],
    'issue corridor tokens',
  );

  console.log('4/6 seeding orderbooks');
  await submit(
    kp.marketMaker,
    fiats.flatMap((f) => [usdcOffer(usdc, corridor[f], FIAT[f].perUsd), fiatOffer(corridor[f], usdc, FIAT[f].perUsd)]),
    'offers',
  );

  console.log('5/6 deploying Stellar Asset Contracts');
  const sac: Record<string, string> = { USDC: await deploySac(kp.usdcIssuer, usdc) };
  for (const f of fiats) sac[FIAT[f].code] = await deploySac(kp.corridorIssuer, corridor[f]);

  console.log('6/6 verifying strict-receive paths (recipient gets 1000)');
  for (const f of fiats.filter((x) => x !== 'MXN')) {
    const res = await horizon.strictReceivePaths([corridor.MXN], corridor[f], '1000').call();
    const best = res.records[0];
    if (!best) throw new Error(`no path TESTMXN -> ${FIAT[f].code}`);
    const hops = [best.source_asset_code, ...best.path.map((p) => p.asset_code ?? 'XLM'), best.destination_asset_code];
    console.log(`  ${hops.join(' -> ')}: pay ${best.source_amount} TESTMXN`);
  }

  writeFileSync(TESTNET_TS, renderTestnetTs(
    Object.fromEntries(Object.entries(kp).map(([k, v]) => [k, v.publicKey()])) as Record<Role | 'clientDomainSigner', string>, sac));

  console.log(`\nwrote ${ENV_PATH} and ${TESTNET_TS}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
