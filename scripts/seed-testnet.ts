/**
 * Creates every testnet account and asset Corra needs, seeds the DEX, and writes:
 *   .env.testnet                      secrets (gitignored)
 *   packages/shared/src/testnet.ts    public addresses (committed, disclosed by design)
 *
 * Usage: pnpm seed-testnet [--force]
 */
import * as S from '@stellar/stellar-sdk';
import { existsSync, writeFileSync } from 'node:fs';
import { FIAT, type FiatCode } from '../packages/shared/src/corridors';

const HORIZON_URL = 'https://horizon-testnet.stellar.org';
const RPC_URL = 'https://soroban-testnet.stellar.org';
const NP = S.Networks.TESTNET;
const ENV_PATH = '.env.testnet';
const TESTNET_TS = 'packages/shared/src/testnet.ts';

const MM_USDC_BALANCE = 10_000_000;
const ANCHOR_MXN_BALANCE = 10_000_000 * FIAT.MXN.perUsd;
const OFFER_DEPTH_USD = 1_000_000;
const SPREAD = 0.0025;

const horizon = new S.Horizon.Server(HORIZON_URL);
const rpc = new S.rpc.Server(RPC_URL);

const amt = (n: number) => n.toFixed(7);
const price = (n: number) => n.toPrecision(12);

/** Friendbot is rate limited and flaky under parallel calls (CI), so a few retries with backoff. */
async function friendbot(pk: string) {
  for (let attempt = 1; ; attempt++) {
    const r = await fetch(`https://friendbot.stellar.org?addr=${encodeURIComponent(pk)}`,
      { signal: AbortSignal.timeout(30_000) }).catch(() => null);
    if (r?.ok) return;
    // A retry after a lost response finds the account already funded: that is success.
    if (r?.status === 400 && /already funded|createAccountAlreadyExist/i.test(await r.text().catch(() => ''))) return;
    if (attempt >= 4) throw new Error(`friendbot ${r?.status ?? 'unreachable'} for ${pk}`);
    await new Promise((done) => setTimeout(done, 2000 * attempt));
  }
}

async function submit(source: S.Keypair, ops: S.xdr.Operation[], label: string) {
  for (let i = 0; i < ops.length; i += 100) {
    const acct = await horizon.loadAccount(source.publicKey());
    const b = new S.TransactionBuilder(acct, { fee: '1000', networkPassphrase: NP }).setTimeout(120);
    ops.slice(i, i + 100).forEach((op) => b.addOperation(op));
    const tx = b.build();
    tx.sign(source);
    try {
      const r = await horizon.submitTransaction(tx);
      console.log(`  ${label}: ${r.hash}`);
    } catch (e: any) {
      const codes = e?.response?.data?.extras?.result_codes;
      throw new Error(`${label} failed: ${JSON.stringify(codes ?? e.message)}`);
    }
  }
}

async function deploySac(source: S.Keypair, asset: S.Asset): Promise<string> {
  const acct = await rpc.getAccount(source.publicKey());
  let tx = new S.TransactionBuilder(acct, { fee: '100000', networkPassphrase: NP })
    .addOperation(S.Operation.createStellarAssetContract({ asset }))
    .setTimeout(120)
    .build();
  tx = await rpc.prepareTransaction(tx);
  tx.sign(source);
  const sent = await rpc.sendTransaction(tx);
  if (sent.status === 'ERROR') throw new Error(`SAC ${asset.code} send error`);
  for (let i = 0; i < 30; i++) {
    await new Promise((r) => setTimeout(r, 2000));
    const got = await rpc.getTransaction(sent.hash);
    if (got.status === 'SUCCESS') {
      console.log(`  SAC ${asset.code}: ${sent.hash}`);
      return asset.contractId(NP);
    }
    if (got.status === 'FAILED') throw new Error(`SAC ${asset.code} failed: ${sent.hash}`);
  }
  throw new Error(`SAC ${asset.code} timed out: ${sent.hash}`);
}

async function main() {
  if (existsSync(ENV_PATH) && !process.argv.includes('--force')) {
    console.error(`${ENV_PATH} exists. Re-run with --force to create a fresh set of accounts.`);
    process.exit(1);
  }

  const kp = {
    usdcIssuer: S.Keypair.random(),
    corridorIssuer: S.Keypair.random(),
    anchorDistribution: S.Keypair.random(),
    marketMaker: S.Keypair.random(),
    feeSponsor: S.Keypair.random(),
    clientDomainSigner: S.Keypair.random(),
  };

  // Written first so a run that fails halfway never loses the keys of accounts it already funded.
  writeFileSync(
    ENV_PATH,
    [
      '# Generated by scripts/seed-testnet.ts. Stellar TESTNET only. Never commit.',
      `USDC_ISSUER_SECRET=${kp.usdcIssuer.secret()}`,
      `CORRIDOR_ISSUER_SECRET=${kp.corridorIssuer.secret()}`,
      `ANCHOR_DISTRIBUTION_SECRET=${kp.anchorDistribution.secret()}`,
      `MARKET_MAKER_SECRET=${kp.marketMaker.secret()}`,
      `FEE_SPONSOR_SECRET=${kp.feeSponsor.secret()}`,
      `CLIENT_DOMAIN_SIGNING_SECRET=${kp.clientDomainSigner.secret()}`,
      '',
    ].join('\n'),
  );

  console.log('1/6 funding accounts with friendbot');
  await Promise.all(
    [kp.usdcIssuer, kp.corridorIssuer, kp.anchorDistribution, kp.marketMaker, kp.feeSponsor].map((k) =>
      friendbot(k.publicKey()),
    ),
  );

  const usdc = new S.Asset('USDC', kp.usdcIssuer.publicKey());
  const fiats = Object.keys(FIAT) as FiatCode[];
  const corridor = Object.fromEntries(
    fiats.map((f) => [f, new S.Asset(FIAT[f].code, kp.corridorIssuer.publicKey())]),
  ) as Record<FiatCode, S.Asset>;

  console.log('2/6 trustlines');
  await submit(
    kp.marketMaker,
    [usdc, ...fiats.map((f) => corridor[f])].map((asset) => S.Operation.changeTrust({ asset })),
    'market-maker trustlines',
  );
  await submit(kp.anchorDistribution, [S.Operation.changeTrust({ asset: corridor.MXN })], 'anchor trustline');

  console.log('3/6 issuing');
  await submit(
    kp.usdcIssuer,
    [S.Operation.payment({ destination: kp.marketMaker.publicKey(), asset: usdc, amount: amt(MM_USDC_BALANCE) })],
    'issue USDC',
  );
  await submit(
    kp.corridorIssuer,
    [
      ...fiats.map((f) =>
        S.Operation.payment({
          destination: kp.marketMaker.publicKey(),
          asset: corridor[f],
          amount: amt(MM_USDC_BALANCE * FIAT[f].perUsd),
        }),
      ),
      S.Operation.payment({
        destination: kp.anchorDistribution.publicKey(),
        asset: corridor.MXN,
        amount: amt(ANCHOR_MXN_BALANCE),
      }),
    ],
    'issue corridor tokens',
  );

  console.log('4/6 seeding orderbooks');
  await submit(
    kp.marketMaker,
    fiats.flatMap((f) => {
      const r = FIAT[f].perUsd;
      return [
        // MM sells USDC, asks slightly more fiat than mid (price = fiat per USDC).
        S.Operation.manageSellOffer({
          selling: usdc,
          buying: corridor[f],
          amount: amt(OFFER_DEPTH_USD),
          price: price(r * (1 + SPREAD)),
        }),
        // MM sells fiat, asks slightly more USDC than mid (price = USDC per fiat).
        S.Operation.manageSellOffer({
          selling: corridor[f],
          buying: usdc,
          amount: amt(OFFER_DEPTH_USD * r),
          price: price((1 / r) * (1 + SPREAD)),
        }),
      ];
    }),
    'offers',
  );

  console.log('5/6 deploying Stellar Asset Contracts');
  const sac: Record<string, string> = { USDC: await deploySac(kp.usdcIssuer, usdc) };
  for (const f of fiats) sac[FIAT[f].code] = await deploySac(kp.corridorIssuer, corridor[f]);

  console.log('6/6 verifying strict-receive paths (recipient gets 1000)');
  for (const f of fiats.filter((x) => x !== 'MXN')) {
    const res = await horizon.strictReceivePaths([corridor.MXN], corridor[f], '1000').call();
    const best = res.records[0];
    if (!best) throw new Error(`no path TESTMXN -> ${FIAT[f].code}`);
    const hops = [best.source_asset_code, ...best.path.map((p) => p.asset_code ?? 'XLM'), best.destination_asset_code];
    console.log(`  ${hops.join(' -> ')}: pay ${best.source_amount} TESTMXN`);
  }

  writeFileSync(
    TESTNET_TS,
    `// Generated by scripts/seed-testnet.ts on ${new Date().toISOString()}.
// Public testnet addresses of team-controlled accounts, disclosed by design.
export const TESTNET = {
  horizonUrl: '${HORIZON_URL}',
  rpcUrl: '${RPC_URL}',
  networkPassphrase: '${NP}',
  usdcIssuer: '${kp.usdcIssuer.publicKey()}',
  corridorIssuer: '${kp.corridorIssuer.publicKey()}',
  anchorDistribution: '${kp.anchorDistribution.publicKey()}',
  marketMaker: '${kp.marketMaker.publicKey()}',
  feeSponsor: '${kp.feeSponsor.publicKey()}',
  clientDomainSigner: '${kp.clientDomainSigner.publicKey()}',
  sac: ${JSON.stringify(sac, null, 4).replace(/\n}/, '\n  }')},
} as const;
`,
  );

  console.log(`\nwrote ${ENV_PATH} and ${TESTNET_TS}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
